#!/usr/bin/env node
/**
 * Çekirdek özel hukuk graf + coverage YAML üretir.
 *   node scripts/lib/write-course-graphs.mjs
 */
import { writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');

function I(id, title, definition, elements, links, kanunId, maddeler, doctrine) {
    return {
        id,
        title,
        definition,
        elements,
        organicLinks: links,
        statuteRefs: maddeler.map((m) => ({ kanunId, maddeNo: String(m) })),
        caseRefs: [],
        doctrineSplit: doctrine,
    };
}

function assertMaddeler(graph) {
    const missing = [];
    for (const inst of graph.institutions) {
        if (inst.definition.length < 40) missing.push(`${inst.id} tanım kısa`);
        if (inst.elements.length < 3) missing.push(`${inst.id} unsur < 3`);
        for (const ref of inst.statuteRefs) {
            const p = join(ROOT, 'content/mevzuat', ref.kanunId, `madde-${ref.maddeNo}.md`);
            if (!existsSync(p)) missing.push(`${inst.id} ${ref.kanunId}/${ref.maddeNo}`);
        }
    }
    if (missing.length) throw new Error(`eksik madde:\n${missing.join('\n')}`);
}

function yamlOf(graph) {
    const lines = [
        `# Denetçi manifesti — ${graph.title}`,
        `courseCode: ${graph.courseCode}`,
        `title: ${graph.title}`,
        `kanun: ${graph.kanunId}`,
        'guz:',
        ...graph.guzInstitutionIds.map((id) => `  - ${id}`),
        'bahar:',
        ...graph.baharInstitutionIds.map((id) => `  - ${id}`),
        'institutions:',
    ];
    for (const inst of graph.institutions) {
        lines.push(`  - id: ${inst.id}`);
        lines.push(`    title: ${inst.title}`);
        lines.push(`    maddeler: [${inst.statuteRefs.map((r) => `'${r.maddeNo}'`).join(', ')}]`);
    }
    return `${lines.join('\n')}\n`;
}

