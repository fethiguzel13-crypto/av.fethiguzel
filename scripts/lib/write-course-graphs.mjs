function main() {
    const gDir = join(ROOT, 'lib/ders-notlari/graphs');
    const cDir = join(ROOT, 'docs/ders-notlari/coverage');
    mkdirSync(gDir, { recursive: true });
    mkdirSync(cDir, { recursive: true });
    for (const graph of GRAPHS) {
        assertMaddeler(graph);
        writeFileSync(join(gDir, `${graph.courseCode}.json`), `${JSON.stringify(graph, null, 4)}\n`, 'utf8');
        writeFileSync(join(cDir, `${graph.courseCode}.yaml`), yamlOf(graph), 'utf8');
        console.log(`[ok] ${graph.courseCode} institutions=${graph.institutions.length}`);
    }
}

main();
